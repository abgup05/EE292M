"""The recorded filing comparison the page can show (``src/web/sample-changes.json``).

It is a real record, written once by ``make changes`` from filings fetched from SEC
EDGAR. These tests keep it a record the current models accept, and check that its
counts, its lists, its links and its marked-up paragraphs agree with one another, so
that a sample regenerated by a broken comparison cannot be committed unnoticed. The
second half damages a copy in each way the checks are meant to notice and expects
every one of them to be reported: the checks are shown failing, not assumed to work.
That every line of a filing is counted once is tested on real filings in
``tests/test_filing_diff.py``; a record alone cannot show it.
"""

from __future__ import annotations

import json
from collections.abc import Callable

import pytest

from app.api import WEB_DIR
from app.core.change_models import (
    ChangeCounts,
    FilingChanges,
    ItemChanges,
    Paragraph,
    WordChange,
)
from app.core.filing_diff import MAX_LISTED, MIN_PARAGRAPH_CHARS, REWORD_THRESHOLD

SAMPLE = WEB_DIR / "sample-changes.json"
COUNTS = tuple(ChangeCounts.model_fields)


def load_sample() -> FilingChanges:
    """The committed sample, validated as the record the API returns."""
    payload = json.loads(SAMPLE.read_text(encoding="utf-8"))
    assert set(payload) == {"note", "changes"}
    assert payload["note"].strip()
    return FilingChanges.model_validate(payload["changes"])


def listed(item: ItemChanges) -> list[tuple[str, int, int, bool]]:
    """(list name, its count, how many are listed, whether it is marked truncated)."""
    return [
        ("added", item.added, len(item.added_paragraphs), item.truncated.added),
        ("removed", item.removed, len(item.removed_paragraphs), item.truncated.removed),
        ("reworded", item.reworded, len(item.reworded_paragraphs), item.truncated.reworded),
        (
            "numbers only",
            item.numbers_only,
            len(item.numbers_only_paragraphs),
            item.truncated.numbers_only,
        ),
    ]


MONTHS = frozenset(
    "january february march april may june july august september october november december".split()
)


def words_apart_from_figures(paragraph: Paragraph) -> list[str]:
    """The paragraph's words without any that holds a digit or names a month.

    Written apart from the comparison's own masking, so that the two can disagree.
    """
    words = [word.lower().strip(",.;:()") for word in paragraph.text.split()]
    return [word for word in words if word not in MONTHS and not any(c.isdigit() for c in word)]


def wrong_link(paragraph: Paragraph, filing_url: str) -> bool:
    """Whether the paragraph's link leaves its filing or does not do what its kind says."""
    located = ":~:text=" in paragraph.link
    kinds = {"passage": True, "first-line": True, "document": False}
    return (
        not paragraph.link.startswith(filing_url)
        or paragraph.link_kind not in kinds
        or kinds[paragraph.link_kind] != located
    )


def problems(changes: FilingChanges) -> list[str]:
    """Every way in which ``changes`` disagrees with itself; empty for a sound record."""
    found: list[str] = []
    earlier, later = changes.earlier, changes.later
    if earlier.form != later.form:
        found.append("the two filings are of different forms")
    if not (earlier.period_end < later.period_end and earlier.filed_date < later.filed_date):
        found.append("the earlier filing is not earlier")
    if earlier.url == later.url:
        found.append("one filing is compared with itself")
    for count in COUNTS:
        if getattr(changes.totals, count) != sum(getattr(item, count) for item in changes.items):
            found.append(f"total {count} is not the sum over the items")
    for item in changes.items:
        for name, count, shown, truncated in listed(item):
            if shown != min(count, MAX_LISTED):
                found.append(f"{item.item}: {name} lists {shown} of {count}")
            if truncated != (count > MAX_LISTED):
                found.append(f"{item.item}: {name} truncation flag is wrong")
        for paragraph in item.added_paragraphs:
            if wrong_link(paragraph, later.url):
                found.append(f"{item.item}: an added paragraph does not link into the later filing")
            if len(paragraph.text) < MIN_PARAGRAPH_CHARS:
                found.append(f"{item.item}: an added paragraph is shorter than a paragraph")
        for paragraph in item.removed_paragraphs:
            if wrong_link(paragraph, earlier.url):
                found.append(f"{item.item}: a removed paragraph does not link into the earlier one")
            if len(paragraph.text) < MIN_PARAGRAPH_CHARS:
                found.append(f"{item.item}: a removed paragraph is shorter than a paragraph")
        for pair in item.reworded_paragraphs:
            if not REWORD_THRESHOLD <= pair.similarity <= 1.0:
                found.append(f"{item.item}: a reworded pair is below the threshold")
        for pair in (*item.reworded_paragraphs, *item.numbers_only_paragraphs):
            if wrong_link(pair.after, later.url):
                found.append(f"{item.item}: a pair does not link into the later filing")
            if wrong_link(pair.before, earlier.url):
                found.append(f"{item.item}: a pair does not link into the earlier one")
            after = " ".join(s.text for s in pair.segments if s.kind in ("same", "added"))
            before = " ".join(s.text for s in pair.segments if s.kind in ("same", "removed"))
            if after.split() != pair.after.text.split():
                found.append(f"{item.item}: the segments do not rebuild the later paragraph")
            if before.split() != pair.before.text.split():
                found.append(f"{item.item}: the segments do not rebuild the earlier paragraph")
        for pair in item.numbers_only_paragraphs:
            before = words_apart_from_figures(pair.before)
            after = words_apart_from_figures(pair.after)
            if before != after or pair.before.text == pair.after.text:
                found.append(f"{item.item}: a numbers-only pair differs in more than figures")
        if set(item.subheadings_added) & set(item.subheadings_removed):
            found.append(f"{item.item}: a sub-heading is both added and removed")
    return found


@pytest.fixture(scope="module")
def sample() -> FilingChanges:
    return load_sample()


def test_the_recorded_sample_agrees_with_itself(sample: FilingChanges) -> None:
    assert problems(sample) == []


def test_the_recorded_sample_shows_every_kind_of_change(sample: FilingChanges) -> None:
    """The page's sample is only a useful demonstration if each kind and a cut list appear."""
    assert sample.totals.added and sample.totals.removed and sample.totals.reworded
    assert sample.totals.unchanged and sample.totals.numbers_only
    assert sample.totals.minor_unchanged and sample.totals.minor_numbers_only
    assert any(item.numbers_only_paragraphs for item in sample.items)
    assert any(item.subheadings_added for item in sample.items)
    assert any(item.subheadings_removed for item in sample.items)
    links = {p.link_kind for item in sample.items for p in item.added_paragraphs}
    assert {"passage", "document"} <= links
    assert any(truncated for item in sample.items for *_, truncated in listed(item))
    kinds = {
        segment.kind
        for item in sample.items
        for pair in item.reworded_paragraphs
        for segment in pair.segments
    }
    assert kinds == {"same", "added", "removed"}


def risk_factors(changes: FilingChanges) -> ItemChanges:
    return next(item for item in changes.items if item.item.startswith("Item 1A"))


def miscount_a_total(changes: FilingChanges) -> None:
    changes.totals.added += 1


def drop_a_listed_paragraph(changes: FilingChanges) -> None:
    risk_factors(changes).added_paragraphs.pop()


def claim_a_full_list_was_cut(changes: FilingChanges) -> None:
    item = next(item for item in changes.items if 0 < item.removed <= MAX_LISTED)
    item.truncated.removed = True


def link_an_added_paragraph_into_the_earlier_filing(changes: FilingChanges) -> None:
    paragraph = risk_factors(changes).added_paragraphs[0]
    paragraph.link = paragraph.link.replace(changes.later.url, changes.earlier.url)


def link_a_removed_paragraph_into_the_later_filing(changes: FilingChanges) -> None:
    paragraph = risk_factors(changes).removed_paragraphs[0]
    paragraph.link = paragraph.link.replace(changes.earlier.url, changes.later.url)


def lose_a_changed_word(changes: FilingChanges) -> None:
    pair = next(
        pair
        for pair in risk_factors(changes).reworded_paragraphs
        if any(segment.kind == "added" for segment in pair.segments)
    )
    pair.segments.remove(next(s for s in pair.segments if s.kind == "added"))


def pair_two_unlike_paragraphs(changes: FilingChanges) -> None:
    risk_factors(changes).reworded_paragraphs[0].similarity = REWORD_THRESHOLD - 0.01


def call_a_bare_link_a_passage_link(changes: FilingChanges) -> None:
    paragraph = next(
        p for item in changes.items for p in item.added_paragraphs if p.link_kind == "document"
    )
    paragraph.link_kind = "passage"


def change_a_word_in_a_numbers_only_pair(changes: FilingChanges) -> None:
    item = next(item for item in changes.items if item.numbers_only_paragraphs)
    pair = item.numbers_only_paragraphs[0]
    pair.after.text += " substantially"
    pair.segments.append(WordChange(text="substantially", kind="added"))


def list_a_sub_heading_on_both_sides(changes: FilingChanges) -> None:
    item = next(item for item in changes.items if item.subheadings_added)
    item.subheadings_removed.append(item.subheadings_added[0])


def swap_the_two_filings(changes: FilingChanges) -> None:
    changes.earlier, changes.later = changes.later, changes.earlier


@pytest.mark.parametrize(
    ("damage", "reported"),
    [
        (miscount_a_total, "total added is not the sum"),
        (drop_a_listed_paragraph, "added lists"),
        (claim_a_full_list_was_cut, "truncation flag"),
        (link_an_added_paragraph_into_the_earlier_filing, "does not link into the later"),
        (link_a_removed_paragraph_into_the_later_filing, "does not link into the earlier"),
        (lose_a_changed_word, "do not rebuild the later paragraph"),
        (pair_two_unlike_paragraphs, "below the threshold"),
        (call_a_bare_link_a_passage_link, "does not link into the later"),
        (change_a_word_in_a_numbers_only_pair, "differs in more than figures"),
        (list_a_sub_heading_on_both_sides, "both added and removed"),
        (swap_the_two_filings, "the earlier filing is not earlier"),
    ],
)
def test_each_kind_of_damage_to_the_record_is_reported(
    sample: FilingChanges, damage: Callable[[FilingChanges], None], reported: str
) -> None:
    damaged = sample.model_copy(deep=True)
    damage(damaged)
    found = problems(damaged)
    assert any(reported in problem for problem in found), found
