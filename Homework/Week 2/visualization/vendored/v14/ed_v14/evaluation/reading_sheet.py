"""A reading sheet of the golden set, for the person who has to check it.

``python -m app.evaluation.reading_sheet [--out eval/golden-reading.md]`` (``make
golden-sheet``) writes every golden case as one short block a person can read in a
minute: the claim, the stance the case expects and the drafter's reason, each excerpt
the case says must be found with a link that opens the filing at it, what the tool did
with the case in the newest recorded evaluation, and a line to tick.

The golden set was drafted by a model. Until a person has read it, every number of the
evaluation measures agreement with that model. This module changes nothing: it only
lays the cases out. Corrections go into ``eval/golden.json`` by hand, and the rule in
``AGENTS.md`` applies: never change an expected value to make a result pass.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from ed_v14.core.links import passage_link
from ed_v14.evaluation.corpus import EVAL_DIR, PinnedFiling, load_pins
from ed_v14.evaluation.golden import GOLDEN_PATH, GoldenCase, read_golden

DEFAULT_OUT = EVAL_DIR / "golden-reading.md"
RESULTS_DIR = EVAL_DIR / "results"
EXPECTED_WORDS = {
    "supports": "the filings SUPPORT the claim",
    "challenges": "the filings CHALLENGE the claim",
    "mixed": "the filings point BOTH WAYS",
    "none": "the filings DO NOT ADDRESS the claim (the tool should refuse to judge it)",
}
INTRO = """# The golden set, to be read

{count} cases over {companies} companies; {unanswerable} of them are claims the filings do not
address. Each was drafted by a model from the filing text and checked mechanically (every
excerpt is in the filing it names). **No person has read them.** Until one has, every number
in `eval/results/` measures agreement with that model.

For each case: read the claim, open the excerpts in the filing, and decide whether the expected
stance is right. Tick one box. Where you disagree, correct `expected` (or the claim, or the
excerpts) in `eval/golden.json`, run `make eval-validate`, and run the evaluation again
(`eval/README.md`). Do not change an expected value because the tool disagreed with it: decide
which of the two is wrong.

This sheet is generated by `make golden-sheet` from `eval/golden.json`, `eval/filings.json` and
{results}. Do not edit it; edit the golden file and generate it again.
"""


def newest_results(directory: Path = RESULTS_DIR) -> Path | None:
    """The newest checked generation record, else the newest generation record, else None."""
    for pattern in ("generation-checked-*.json", "generation-*.json"):
        found = sorted(directory.glob(pattern))
        if found:
            return found[-1]
    return None


def outcomes(path: Path | None) -> dict[str, Mapping[str, Any]]:
    """What the tool did with each case in a recorded evaluation, by case id."""
    if path is None:
        return {}
    record = json.loads(path.read_text(encoding="utf-8"))
    return {case["case_id"]: case for case in record.get("cases", [])}


def disagrees(case: GoldenCase, outcome: Mapping[str, Any] | None) -> bool:
    """Whether a recorded evaluation judged the case differently from what the case expects."""
    if outcome is None:
        return False
    if case.kind == "unanswerable":
        return not outcome.get("refused")
    return not outcome.get("agrees")


def _tool_line(case: GoldenCase, outcome: Mapping[str, Any] | None) -> str:
    if outcome is None:
        return "**What the tool did:** no recorded evaluation covers this case."
    verdict = str(outcome.get("verdict") or "none")
    if case.kind == "unanswerable":
        refused = bool(outcome.get("refused"))
        did = "refused to judge it, as expected" if refused else f"judged it ({verdict})"
        return f"**What the tool did (recorded answers):** {did}."
    agrees = "agrees with" if outcome.get("agrees") else "DISAGREES with"
    found = (
        "one of these excerpts was among the passages the engine was shown"
        if outcome.get("retrieval_hit")
        else "none of these excerpts was among the passages the engine was shown"
    )
    return (
        f"**What the tool did (recorded answers):** verdict {verdict!r}, which {agrees} "
        f"the expected stance; {found}."
    )


def render_case(
    number: int,
    case: GoldenCase,
    pins: Mapping[str, PinnedFiling],
    outcome: Mapping[str, Any] | None,
) -> list[str]:
    """One case as a block of Markdown lines."""
    company = next((pins[a].name for a in case.filings if a in pins), case.ticker)
    lines = [f"## {number}. {case.id} ({company})", "", f"**Claim:** {case.claim}", ""]
    lines += [
        f"**Expected:** {EXPECTED_WORDS[case.expected]}. *The drafter's reason:* {case.why}",
        "",
    ]
    if case.must_retrieve:
        lines += ["**The excerpts a right answer would rest on:**", ""]
        for position, record in enumerate(case.must_retrieve, start=1):
            pin = pins.get(record.accession)
            where = f"{pin.form} for the period ended {pin.period_end}" if pin else record.accession
            link = f" [open in the filing]({passage_link(pin.url, record.text)})" if pin else ""
            lines += [f"{position}. {where}, {record.section}:{link}", ""]
            lines += [f"   > {record.text}", ""]
    else:
        read = ", ".join(
            f"{pins[a].form} {pins[a].period_end}" if a in pins else a for a in case.filings
        )
        lines += [
            f"**No excerpt:** the case says nothing in the filings read ({read}) bears on it.",
            "",
        ]
    lines += [_tool_line(case, outcome), ""]
    lines += ["- [ ] The expected stance is right"]
    lines += ["- [ ] It is wrong, or the claim is badly posed:", ""]
    return lines


def render_sheet(
    cases: Sequence[GoldenCase],
    pins: Mapping[str, PinnedFiling],
    recorded: Mapping[str, Mapping[str, Any]],
    results_name: str,
) -> str:
    """The whole sheet: the introduction, then every case in the golden file's order."""
    intro = INTRO.format(
        count=len(cases),
        companies=len({case.ticker for case in cases}),
        unanswerable=sum(case.kind == "unanswerable" for case in cases),
        results=f"`eval/results/{results_name}`" if results_name else "no recorded evaluation",
    )
    lines = [intro]
    apart = [
        f"{number} ({case.id})"
        for number, case in enumerate(cases, start=1)
        if disagrees(case, recorded.get(case.id))
    ]
    if apart:
        lines += [
            "**Start with these**, where the tool's recorded answer and the expected stance "
            f"part ways, so one of the two is wrong: {', '.join(apart)}.",
            "",
        ]
    for number, case in enumerate(cases, start=1):
        lines += render_case(number, case, pins, recorded.get(case.id))
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write the sheet and say where."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    raw, _ = read_golden(GOLDEN_PATH)
    cases = [GoldenCase.model_validate(item) for item in raw["cases"]]
    results = newest_results()
    sheet = render_sheet(cases, load_pins(), outcomes(results), results.name if results else "")
    args.out.write_text(sheet, encoding="utf-8")
    print(f"golden-sheet: wrote {args.out} ({len(cases)} cases)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
